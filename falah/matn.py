"""فصل متن الحديث عن سنده، واستخراج الصحابي الراوي.

قاعدة الملف: لا يُخترع حرف. كل ما هنا قصٌّ من النص الأصلي، ومع كل نتيجة
درجة ثقة. ما لم تبلغ ثقته الحدَّ لا يصلح للبطاقة، ويُعلَّم `blocked`.
"""
import re
from .text import clean, searchable

PROPHET = r"(?:صلى\s*الله\s*عليه\s*و?سلم|ﷺ|صَلَّى\s*اللَّهُ\s*عَلَيْهِ\s*وَسَلَّمَ)"

# صيغ افتتاح المتن بعد السند
INTRO = re.compile(
    PROPHET + r"[^\wء-ي]*(?:[،:]\s*)?(?:أَنَّهُ\s*)?(?:قَالَ|قال|يَقُولُ|يقول)?\s*[:،]?\s*",
)
QUOTE = re.compile(r'"([^"]{12,})"')

# كبار الرواة من الصحابة — تُستعمل للتحقق لا للتخمين
COMPANIONS = [
    "أبو هريرة","عبد الله بن عمر","ابن عمر","أنس بن مالك","عائشة","عبد الله بن عباس","ابن عباس",
    "جابر بن عبد الله","أبو سعيد الخدري","عبد الله بن مسعود","ابن مسعود","عمر بن الخطاب",
    "علي بن أبي طالب","أبو موسى الأشعري","المغيرة بن شعبة","سعد بن أبي وقاص","أبو بكر الصديق",
    "عثمان بن عفان","معاذ بن جبل","حذيفة بن اليمان","سهل بن سعد","النعمان بن بشير",
    "البراء بن عازب","عبد الله بن عمرو","أبي بن كعب","زيد بن ثابت","بريدة","عبد الله بن الزبير",
    "أم سلمة","ثوبان","تميم الداري","وائل بن حجر","عقبة بن عامر","أسامة بن زيد","أبو ذر",
    "سلمان الفارسي","بلال بن رباح","عمار بن ياسر","أبو أيوب الأنصاري","جرير بن عبد الله",
    "أبو الدرداء","معاوية بن أبي سفيان","أبو قتادة","سمرة بن جندب","عمران بن حصين",
    "أبو بكرة","صفوان بن عسال","أم سليم","أسماء بنت أبي بكر","حكيم بن حزام","رافع بن خديج",
]
_COMP_IDX = [(c, searchable(c)) for c in COMPANIONS]

def extract_matn(arabic: str):
    """يعيد (المتن، الطريقة، الثقة 0–1). لا يُعيد نصًا لم يرد في الأصل."""
    t = clean(arabic).replace("\n", " ")
    t = re.sub(r"\s+", " ", t)

    # ١) علامة الاقتباس في الطبعة — أقوى إشارة، وهي من الناشر لا منّا
    qs = QUOTE.findall(t)
    if qs:
        m = max(qs, key=len).strip(" ‏«»:،")
        if len(m) >= 12:
            return m, "quotation-marks", 0.95

    # ٢) ما بعد ذكر النبي ﷺ وصيغة القول
    hits = list(INTRO.finditer(t))
    if hits:
        m = t[hits[-1].end():].strip(' "‏«»:،')
        if len(m) >= 12:
            return m, "post-prophet-marker", 0.7

    # ٣) لم نستطع الفصل بثقة — لا نخمّن
    return None, "unresolved", 0.0

def extract_narrator(arabic: str):
    """الصحابي الراوي: يُلتقط من السند ثم يُطابَق بقائمة معروفة. بلا مطابقة = بلا ادعاء."""
    s = searchable(arabic)
    best = None
    for name, key in _COMP_IDX:
        i = s.find(key)
        if i >= 0 and (best is None or i > best[1]):   # الأقرب إلى المتن آخر السند
            best = (name, i)
    return (best[0], 0.9) if best else (None, 0.0)

# كلامٌ للمصنّف أو للرواة لا يصحّ أن يُنسب متنًا
INTRUDERS = ["قال ابو عيسي", "وفي الباب", "حدثنا", "اخبرنا", "حدثني",
             "قال الشيخ", "قال ابو داود", "هذا حديث", "سالت", "قال ابو عبد الرحمن"]

# لا يبدأ متنٌ بحرف عطف أو جرّ — علامة على قصٍّ في منتصف الجملة
BAD_STARTS = ["و", "ف", "ثم", "علي", "عن", "من", "في", "الي", "او", "ب", "ل",
              "قال", "قالت", "قالوا", "ان", "انه", "بن", "ابن", "كان", "فقال"]

def matn_sane(matn: str) -> tuple[bool, str | None]:
    """حارسٌ يمنع ثلاث آفات: القصّ من منتصف الجملة، ودخول كلام المصنّف،
    وبقايا السند. ما يسقط هنا يُحجب ولا يُصحَّح آليًا."""
    s = searchable(matn)
    if not s: return False, "المتن فارغ"
    words = s.split()
    if words[0] in BAD_STARTS:
        return False, "المتن يبدأ من منتصف الجملة"
    for bad in INTRUDERS:
        if bad in s:
            return False, "المتن يخالطه كلام الرواة أو المصنّف"
    if len(words) < 4:
        return False, "المتن أقصر من أن يُعرض"
    return True, None

def is_card_ready(matn: str | None, conf: float, lo=20, hi=320):
    """هل يصلح للبطاقة؟ لا يُعتمد إلا ما فصلته علامة الاقتباس في الطبعة،
    ثم يمرّ على حارس السلامة، ثم على حدّ الطول."""
    if not matn: return False, "لم يُفصل المتن عن السند"
    if conf < 0.95: return False, "فصل المتن غير مؤكّد — علامة الطبعة غائبة"
    ok, why = matn_sane(matn)
    if not ok: return False, why
    n = len(matn)
    if n < lo:  return False, "المتن أقصر من أن يُعرض"
    if n > hi:  return False, "المتن أطول من مساحة البطاقة"
    return True, None
